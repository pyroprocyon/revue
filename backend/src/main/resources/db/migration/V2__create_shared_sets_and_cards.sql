-- Shared sets and their cards, loaded from the YAML files under content/public (plan section 5).
-- Each shared card exists once, so a correction reaches every student who saved its set.
-- Personal decks arrive in a later migration, which will add cards.deck_id and relax the
-- shared-only constraints below.

CREATE TABLE sets (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stable across file and title renames; the loader finds a set only by this key.
    set_key        text        NOT NULL UNIQUE,
    title          text        NOT NULL,
    description    text        NOT NULL,
    publisher_name text        NOT NULL,
    subject        text        NOT NULL,
    -- Set when the set's file disappears from a validated content source. Savers keep studying it.
    retired_at     timestamptz,
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL
);

CREATE TABLE cards (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id          bigint      NOT NULL REFERENCES sets (id) ON DELETE RESTRICT,
    -- Stable and unique among shared cards; the loader finds a card only by this key.
    content_key     text        NOT NULL UNIQUE,
    -- Order inside the set, rewritten from the file on every load. A sort key, not a unique key.
    position        integer     NOT NULL,
    question        text        NOT NULL,
    answer          text        NOT NULL,
    explanation     text        NOT NULL,
    memory_hook     text,
    source          text        NOT NULL,
    -- One or two short ideas a correct answer must contain, in file order.
    key_ideas       text[]      NOT NULL,
    -- Goes up by one whenever the question, answer, explanation, memory hook, source or key ideas
    -- change. Review logs record the version a student actually saw.
    content_version integer     NOT NULL DEFAULT 1 CHECK (content_version >= 1),
    -- Set when the card disappears from its set's file. A retired card leaves every queue.
    retired_at      timestamptz,
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL,
    CHECK (cardinality(key_ideas) BETWEEN 1 AND 2)
);

CREATE INDEX cards_set_position_idx ON cards (set_id, position, id);

-- Shared sets and cards are retired, never deleted, so students never lose their history
-- (plan section 7). This guard stops the application's role from deleting them, including
-- rows that nobody has studied yet.
CREATE FUNCTION forbid_shared_content_delete() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'Shared % rows are retired, never deleted', TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER sets_are_never_deleted
    BEFORE DELETE ON sets
    FOR EACH ROW EXECUTE FUNCTION forbid_shared_content_delete();

CREATE TRIGGER shared_cards_are_never_deleted
    BEFORE DELETE ON cards
    FOR EACH ROW WHEN (OLD.set_id IS NOT NULL) EXECUTE FUNCTION forbid_shared_content_delete();
